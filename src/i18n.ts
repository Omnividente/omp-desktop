export type UiKey = keyof typeof UI_TEXT.ru

export function resolveLang(lang: Lang | string | null | undefined): Lang {
  return lang === "en" || lang === "zh" ? lang : "ru"
}

export function t(lang: Lang | string | null | undefined, key: UiKey): string {
  return UI_TEXT[resolveLang(lang)][key]
}

